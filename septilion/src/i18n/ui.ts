export function href(route: Route, lang: Lang): string {
  const base = lang === 'hr' ? '' : '/en';
  if (route === 'gate') return base || '/';
  return `${base}/${route}`;
}
export const fill = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
export function plural(n: number, forms: string[]) {
  // hr: 1 stavka, 2–4 stavke, 5+ stavki; en: forms[0] za 1, inače forms[1]
  if (forms[0] === 'item') return n === 1 ? forms[0] : forms[1];
  return n % 10 === 1 && n % 100 !== 11 ? forms[0] : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? forms[1] : forms[2];
}
